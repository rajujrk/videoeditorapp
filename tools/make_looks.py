#!/usr/bin/env python3
"""Generates the built-in looks: 3D LUTs (.cube, 17 points per side) from our own colour
transforms, and effects/looks/looks.json listing every look. Run from the repository root:

    python3 tools/make_looks.py

The transforms below are original: tone curves, split toning, channel mixing and fades on
gamma-encoded RGB. Re-running rewrites the files byte for byte.
"""
import json
import math
import os

SIZE = 17
OUT = os.path.join("effects", "looks")


def clamp(v):
    return min(1.0, max(0.0, v))


def luma(r, g, b):
    return 0.2126 * r + 0.7152 * g + 0.0722 * b


def saturate(c, amount):
    y = luma(*c)
    return tuple(y + (v - y) * amount for v in c)


def s_curve(v, strength):
    """A smooth S around mid grey: 0 leaves v alone, 1 is strong."""
    s = v * v * (3 - 2 * v)  # smoothstep
    return v + (s - v) * strength


def fade(v, black, white):
    return black + v * (white - black)


def split_tone(c, shadows, highlights, amount=1.0):
    y = luma(*c)
    w_shadow = (1 - y) ** 2
    w_light = y ** 2
    return tuple(v + amount * (s * w_shadow + h * w_light) for v, s, h in zip(c, shadows, highlights))


def warm_film(r, g, b):
    c = saturate((r, g, b), 0.9)
    c = split_tone(c, (-0.03, 0.02, 0.05), (0.07, 0.03, -0.06))
    return tuple(fade(s_curve(clamp(v), 0.35), 0.03, 0.98) for v in c)


def teal_orange(r, g, b):
    c = saturate((r, g, b), 1.1)
    c = split_tone(c, (-0.06, 0.04, 0.09), (0.10, 0.03, -0.09))
    return tuple(s_curve(clamp(v), 0.3) for v in c)


def bleach_bypass(r, g, b):
    c = saturate((r, g, b), 0.45)
    return tuple(s_curve(s_curve(clamp(v), 0.6), 0.4) for v in c)


def cool_night(r, g, b):
    c = saturate((r, g, b), 0.7)
    c = (c[0] * 0.85, c[1] * 0.95, c[2] * 1.08 + 0.03)
    return tuple(clamp(v) ** 1.25 for v in c)


def vintage_fade(r, g, b):
    c = saturate((r, g, b), 0.75)
    c = split_tone(c, (0.02, 0.0, 0.04), (0.06, 0.04, -0.07))
    return tuple(fade(s_curve(clamp(v), -0.2), 0.10, 0.92) for v in c)


def sepia(r, g, b):
    y = luma(r, g, b)
    y = s_curve(y, 0.2)
    return (y * 1.07 + 0.02, y * 0.88 + 0.01, y * 0.64)


def cross_process(r, g, b):
    return (s_curve(clamp(r), 0.6), s_curve(clamp(g), 0.3) * 1.02, fade(s_curve(clamp(b), -0.5), 0.12, 0.82))


def noir(r, g, b):
    y = s_curve(s_curve(luma(r, g, b), 0.7), 0.3)
    return (y * 0.98, y * 0.99, y * 1.0 + 0.015 * (1 - y))


def golden_hour(r, g, b):
    c = saturate((r, g, b), 1.12)
    c = (c[0] * 1.07 + 0.02, c[1] * 1.0 + 0.01, c[2] * 0.84)
    c = split_tone(c, (0.04, 0.02, -0.02), (0.03, 0.02, -0.03))
    return tuple(s_curve(clamp(v), 0.15) for v in c)


def matte_pastel(r, g, b):
    c = saturate((r, g, b), 0.72)
    c = split_tone(c, (0.03, 0.0, 0.04), (0.03, 0.01, 0.0))
    return tuple(fade(clamp(v), 0.10, 0.94) for v in c)


LOOKS = [
    # id, title, category, transform (None: no LUT), grade tweaks
    ("warm_film", "Warm Film", "Film", warm_film, {}),
    ("teal_orange", "Teal & Orange", "Cinematic", teal_orange, {}),
    ("bleach_bypass", "Bleach Bypass", "Cinematic", bleach_bypass, {}),
    ("golden_hour", "Golden Hour", "Mood", golden_hour, {}),
    ("cool_night", "Cool Night", "Mood", cool_night, {}),
    ("vintage_fade", "Vintage Fade", "Vintage", vintage_fade, {}),
    ("matte_pastel", "Matte Pastel", "Vintage", matte_pastel, {}),
    ("cross_process", "Cross Process", "Film", cross_process, {}),
    ("sepia", "Sepia", "Mono", sepia, {}),
    ("noir", "Noir", "Mono", noir, {}),
    ("vivid", "Vivid", "Basic", None, {"saturation": 0.35, "contrast": 0.15}),
    ("black_white", "Black & White", "Mono", None, {"saturation": -1.0, "contrast": 0.1}),
]


def write_cube(name, title, transform):
    lines = [f'TITLE "{title}"', "# TechieVideoEditor built-in look, generated by tools/make_looks.py",
             f"LUT_3D_SIZE {SIZE}"]
    for b in range(SIZE):
        for g in range(SIZE):
            for r in range(SIZE):
                out = transform(r / (SIZE - 1), g / (SIZE - 1), b / (SIZE - 1))
                lines.append(" ".join(f"{clamp(v):.4f}" for v in out))
    with open(os.path.join(OUT, "luts", name + ".cube"), "w") as f:
        f.write("\n".join(lines) + "\n")


def main():
    os.makedirs(os.path.join(OUT, "luts"), exist_ok=True)
    looks = []
    for look_id, title, category, transform, grade in LOOKS:
        entry = {"id": look_id, "title": title, "category": category, "grade": dict(grade)}
        if transform:
            write_cube(look_id, title, transform)
            entry["grade"]["lutPath"] = f":/effects/looks/luts/{look_id}.cube"
        looks.append(entry)
    with open(os.path.join(OUT, "looks.json"), "w") as f:
        json.dump({"looks": looks, "license": "TVE-Original"}, f, indent=2)
        f.write("\n")


if __name__ == "__main__":
    main()
