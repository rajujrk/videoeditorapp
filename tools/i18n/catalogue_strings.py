#!/usr/bin/env python3
"""Writes ui/player/CatalogueStrings.cpp: the names in the built-in catalogues under effects/
(effects and their settings, looks, music and sounds, stickers, export presets), marked for lupdate so they
are translated with the app's own strings (shown through catalogueText()).

Run it after changing a catalogue (then update_translations); the tve_catalogue_strings
test fails while the file is out of date.
    python3 tools/i18n/catalogue_strings.py [--check]
"""
import json
import pathlib
import sys

ROOT = pathlib.Path(__file__).resolve().parents[2]
OUT = ROOT / "ui/player/CatalogueStrings.cpp"


def english(title):
    return title.get("en") if isinstance(title, dict) else title


def names():
    found = []

    def add(text):
        if isinstance(text, str) and text.strip() and text not in found:
            found.append(text)

    for manifest in sorted((ROOT / "effects").rglob("manifest.json")):
        m = json.loads(manifest.read_text())
        add(english(m.get("title")))
        for p in m.get("params", []):
            add(english(p.get("title")))
            for v in p.get("values", []):
                add(v)
    for look in json.loads((ROOT / "effects/looks/looks.json").read_text())["looks"]:
        add(look.get("title"))
        add(look.get("category"))
    for recipe in sorted((ROOT / "effects/sounds").glob("*/recipe.json")):
        add(english(json.loads(recipe.read_text()).get("title")))
    for preset in json.loads((ROOT / "ui/player/export_presets.json").read_text())["presets"]:
        add(preset.get("title"))
        add(preset.get("description"))
    for sticker in json.loads((ROOT / "effects/stickers/stickers.json").read_text())["stickers"]:
        add(sticker.get("title"))
    return found


def source():
    lines = [
        "// Generated by tools/i18n/catalogue_strings.py from effects/ — do not edit. The names in",
        "// the built-in catalogues, for lupdate; the app shows them through catalogueText().",
        "#include <QtGlobal>",
        "",
        "namespace {",
        "",
        "[[maybe_unused]] const char* const kCatalogueStrings[] = {",
    ]
    for text in names():
        lines.append("    QT_TRANSLATE_NOOP(\"catalogue\", " + json.dumps(text, ensure_ascii=False) + "),")
    lines += ["};", "", "} // namespace", ""]
    return "\n".join(lines)


if __name__ == "__main__":
    text = source()
    if "--check" in sys.argv:
        if not OUT.exists() or OUT.read_text() != text:
            sys.exit(f"{OUT.relative_to(ROOT)} is out of date: run tools/i18n/catalogue_strings.py")
        sys.exit(0)
    OUT.write_text(text)
    print(f"{OUT.relative_to(ROOT)}: {text.count('QT_TRANSLATE_NOOP')} names")
